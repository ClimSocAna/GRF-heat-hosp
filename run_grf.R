set.seed(1234)

#load functions
source("functions.R")

# read in environment variables from SLURM --------------------------------
##analyses was run on HPC with a slurm script of the following format
##to allow for using environment variables from SLURM in R script

# export summer="yes" #use only summer data?
# export EMs="imp_red_settledic"  #which effect modifiers? imp, imp_red_settledic, gisd, gisd_nohum
# export heat_def="perc_98th" #can be perc_98th, heatwave, lag1, lag2, abs_24, comb_current_lag
